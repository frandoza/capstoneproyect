import assert from "node:assert/strict";
import { readFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || "playwright");
const base = process.env.TEST_BASE_URL || "http://localhost:5173";
const password = readFileSync(new URL("../.dev.vars", import.meta.url), "utf8").match(/^LOCAL_ADMIN_PASSWORD=(.+)$/m)?.[1].trim();
assert(password, "Local password configured");
const browser = await chromium.launch({ headless: true, channel: process.env.TEST_BROWSER || "msedge" });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
mkdirSync("outputs/verification", { recursive: true });
const stamp = Date.now();
try {
  let response = await context.request.get(base + "/api/requests");
  assert.equal(response.status(), 401, "Anonymous cannot read requests");
  response = await context.request.post(base + "/api/requests", { headers: { Origin: "https://foreign.example" }, data: {} });
  assert.equal(response.status(), 403, "Cross-origin write blocked");
  response = await context.request.post(base + "/api/requests", { headers: { Origin: base }, data: {} });
  assert.equal(response.status(), 400, "Invalid brief rejected");
  response = await context.request.patch(base + "/api/requests/not-found", { headers: { Origin: base }, data: { status: "Contactada" } });
  assert.equal(response.status(), 401, "Anonymous cannot update");
  await page.goto(base);
  await page.getByRole("heading", { level: 1 }).waitFor();
  await page.waitForFunction(() => !!document.querySelector("canvas"));
  await page.waitForTimeout(1500);
  await page.screenshot({ path: "outputs/verification/desktop-home.png" });
  await page.getByRole("button", { name: "Ver aplicación: Bebidas", exact: true }).click();
  await page.getByRole("button", { name: "Consultar esta aplicación" }).click();
  await page.getByRole("radio", { name: "Bebidas", exact: true }).waitFor();
  assert(await page.getByRole("radio", { name: "Bebidas", exact: true }).isChecked());
  await page.getByLabel("Perfil de sabor buscado").fill("Limón de prueba");
  await page.getByLabel("Etapa del proyecto").selectOption("Pruebas piloto");
  await page.getByRole("button", { name: "Ver orientación" }).click();
  await page.getByLabel("Empresa", { exact: true }).fill(`DEMO QA ${stamp}`);
  await page.getByLabel("Nombre de contacto").fill("Contacto de prueba");
  await page.getByLabel("Correo electrónico").fill("demo@example.test");
  await page.getByLabel("Producto y matriz").fill("Bebida acuosa de prueba");
  await page.getByRole("button", { name: "Atrás", exact: true }).click();
  assert.equal(await page.getByLabel("Perfil de sabor buscado").inputValue(), "Limón de prueba");
  await page.getByRole("button", { name: "Ver orientación" }).click();
  assert.equal(await page.getByLabel("Empresa", { exact: true }).inputValue(), `DEMO QA ${stamp}`);
  await page.getByLabel("Autorizo el registro").check();
  await page.getByRole("button", { name: "Revisar solicitud" }).click();
  assert((await page.getByRole("region", { name: "Resumen de solicitud" }).innerText()).includes(`DEMO QA ${stamp}`));
  await page.getByRole("button", { name: "Atrás", exact: true }).click();
  assert.equal(await page.getByLabel("Empresa", { exact: true }).inputValue(), `DEMO QA ${stamp}`);
  await page.getByRole("button", { name: "Revisar solicitud" }).click();
  await page.getByRole("button", { name: "Confirmar y registrar" }).click();
  await page.getByRole("heading", { name: "Solicitud registrada" }).waitFor();
  const receiptDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Descargar solicitud", exact: true }).click();
  assert((await receiptDownload).suggestedFilename().endsWith('.txt'));
  await page.goto(base + "/admin");
  await page.getByLabel("Contraseña local").fill(password);
  await page.getByRole("button", { name: "Ingresar", exact: true }).click();
  await page.getByRole("heading", { name: "Solicitudes técnicas" }).waitFor();
  await page.getByLabel("Filtrar por aplicación").selectOption("Bebidas");
  await page.getByLabel("Buscar solicitudes").fill(`DEMO QA ${stamp}`);
  const csvDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar CSV", exact: true }).click();
  assert((await csvDownload).suggestedFilename().endsWith('.csv'));
  const stored = (await (await context.request.get(base + "/api/requests")).json()).requests.find(r => JSON.parse(r.payload).company === `DEMO QA ${stamp}`);
  const brief = JSON.parse(stored.payload);
  response = await context.request.post(base + "/api/requests", { headers: { Origin: base }, data: { ...brief, requestId: stored.id } });
  assert.equal(response.status(), 201, "Identical retry is idempotent");
  response = await context.request.post(base + "/api/requests", { headers: { Origin: base }, data: { ...brief, ph: "15", requestId: crypto.randomUUID() } });
  assert.equal(response.status(), 400, "Invalid pH rejected on server");
  response = await context.request.post(base + "/api/requests", { headers: { Origin: base }, data: { ...brief, consent: false, requestId: crypto.randomUUID() } });
  assert.equal(response.status(), 400, "Consent required on server");
  response = await context.request.patch(base + "/api/requests/" + stored.id, { headers: { Origin: base }, data: { status: "Invalid" } });
  assert.equal(response.status(), 400, "Invalid state rejected");
  await page.getByRole("button", { name: new RegExp(`DEMO QA ${stamp}`) }).click();
  await page.getByLabel("Estado", { exact: true }).selectOption("En revisión");
  await page.waitForFunction(() => [...document.querySelectorAll('.request-status')].some(n => n.textContent === "En revisión"));
  await page.reload();
  await page.getByRole("button", { name: new RegExp(`DEMO QA ${stamp}`) }).waitFor();
  await page.getByRole("button", { name: new RegExp(`DEMO QA ${stamp}`) }).click();
  assert.equal(await page.getByLabel("Estado", { exact: true }).inputValue(), "En revisión");
  await page.screenshot({ path: "outputs/verification/desktop-panel.png", fullPage: true });
  await page.getByRole("button", { name: "Salir", exact: true }).click();
  await page.getByRole("heading", { name: "Acceso al equipo" }).waitFor();
  assert.equal((await context.request.get(base + "/api/requests")).status(), 401, "Logout revokes session");
  for (const width of [390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    await page.goto(base);
    await page.waitForFunction(() => !!document.querySelector("canvas"));
    await page.waitForTimeout(1000);
    await page.getByRole("button", { name: "Abrir menú", exact: true }).click();
    await page.getByRole("navigation", { name: "Navegación móvil" }).getByRole("link", { name: "contacto", exact: true }).click();
    await page.getByRole("radio", { name: "Helados y postres congelados", exact: true }).check();
    await page.getByLabel("Perfil de sabor buscado").fill("Vainilla");
    await page.getByLabel("Etapa del proyecto").selectOption("Idea inicial");
    await page.getByRole("button", { name: "Ver orientación" }).click();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "No horizontal overflow");
    await page.locator(".brief-form").screenshot({ path: `outputs/verification/mobile-form-${width}.png` });
  }
  assert.deepEqual(errors, [], "No browser errors");
  console.log("PASS: protected API, origin checks, validation, selection, back navigation, submission, panel, persistence on reload, status update, logout, mobile 390/768.");
  console.log("A clearly marked DEMO QA request remains in the local panel for inspection.");
} catch (error) {
  await page.screenshot({ path: "outputs/verification/failure.png", fullPage: true });
  console.log(await page.locator("body").innerText());
  console.log("Browser errors:", errors);
  throw error;
} finally { await browser.close(); }
